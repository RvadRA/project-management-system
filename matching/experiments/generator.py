def _history(rng: random.Random, employee_id: str, family: str,
             skills: Sequence[SkillLevel], domain: str, reliability: float) -> Tuple[HistoryTask, ...]:
    rows = []
    skill_names = [item.name for item in skills]
    for index in range(rng.randint(8, 20)):
        task_domain = domain if rng.random() < 0.65 else rng.choice(DOMAINS)
        on_time = rng.random() < reliability
        rows.append(HistoryTask(
            id=f"{employee_id}-H{index + 1:02d}",
            title=f"Историческая задача {index + 1}: {rng.choice(FEATURES[family])}",
            completed_at=(datetime.date(2024, 1, 1) + datetime.timedelta(
                days=rng.randint(0, 680)
            )).isoformat(),
            domain=task_domain,
            on_time=on_time,
            skills=tuple(rng.sample(skill_names, k=min(len(skill_names), rng.randint(1, 3)))),
        ))
    rows.sort(key=lambda item: item.completed_at)
    return tuple(rows)


def _workload(rng: random.Random, employee_index: int, domain: str,
              high_load: bool, no_workload: bool) -> Tuple[Workload, ...]:
    if no_workload:
        return ()
    if high_load:
        load = rng.choice([90, 100])
        return (Workload(
            project_id=f"P{employee_index % 12 + 1:02d}",
            domain=domain,
            start_date="2026-01-01",
            end_date="2026-12-31",
            load_percent=load,
        ),)
    rows = []
    for index in range(rng.randint(1, 3)):
        start = datetime.date(2025, 1, 1) + datetime.timedelta(days=rng.randint(0, 400))
        end = start + datetime.timedelta(days=rng.randint(60, 240))
        rows.append(Workload(
            project_id=f"P{(employee_index + index) % 12 + 1:02d}",
            domain=domain if rng.random() < 0.7 else rng.choice(DOMAINS),
            start_date=start.isoformat(),
            end_date=end.isoformat(),
            load_percent=rng.choice([20, 30, 40, 50, 60, 70, 80]),
        ))
    return tuple(rows)


def _unavailability(rng: random.Random) -> Tuple[Unavailability, ...]:
    rows = []
    for index in range(rng.randint(0, 2)):
        start = datetime.date(2026, 1, 1) + datetime.timedelta(days=rng.randint(0, 240))
        end = start + datetime.timedelta(days=rng.randint(2, 14))
        rows.append(Unavailability(
            type=rng.choice(["VACATION", "SICK_LEAVE", "UNPAID_LEAVE"]),
            start_date=start.isoformat(),
            end_date=end.isoformat(),
        ))
    return tuple(rows)


def _employees(seed: int, count: int) -> List[Employee]:
    rng = random.Random(seed)
    families = ["Backend", "Frontend", "Data", "DevOps", "Design", "Management"]
    high_load_ids = {6, 12, 18, 24, 30}
    no_rate_ids = {3, 9, 15, 21}
    no_workload_ids = {4, 10, 16, 22}
    employees = []
    for index in range(1, count + 1):
        family = families[(index - 1) % len(families)]
        skills = _skill_levels_for_family(rng, family)
        domain = rng.choice(DOMAINS)
        reliability = rng.uniform(0.62, 0.96)
        employee_id = f"E{index:02d}"
        employee = Employee(
            id=employee_id,
            name=f"Synthetic Employee {index:02d}",
            position=rng.choice(POSITIONS[family]),
            domain=domain,
            summary=(
                f"{family} specialist in {domain}; "
                f"skills: {', '.join(item.name for item in skills)}"
            ),
            synthetic=True,
            skills=skills,
            history=_history(rng, employee_id, family, skills, domain, reliability),
            unavailability=_unavailability(rng),
            workload=_workload(rng, index, domain, index in high_load_ids,
                               index in no_workload_ids),
            hourly_rate=(
                None if index in no_rate_ids else
                round({"Backend": 55, "Frontend": 50, "Data": 52, "DevOps": 65,
                       "Design": 45, "Management": 55}[family] + rng.uniform(-10, 20), 1)
            ),
            manual_ratings=tuple(
                ManualRating(score=round(rng.uniform(0.55, 1.0), 2),
                             rated_at=(datetime.date(2025, 1, 1) + datetime.timedelta(
                                 days=rng.randint(0, 330)
                             )).isoformat())
                for _ in range(rng.randint(0, 2))
            ),
        )
        employees.append(employee)
    return employees


def _task_dates(rng: random.Random) -> Tuple[str, str]:
    assigned = datetime.date(2026, 1, 5) + datetime.timedelta(days=rng.randint(0, 170))
    deadline = assigned + datetime.timedelta(days=rng.randint(5, 30))
    return assigned.isoformat(), deadline.isoformat()


def _task_type(family: str) -> str:
    return {
        "Backend": "backend", "Frontend": "frontend", "Data": "data",
        "DevOps": "devops", "Design": "design", "Management": "management",
    }[family]


def _primary_family(skill_names: Sequence[str]) -> str:
    from .catalog import SKILL_BY_NAME
    counts = {}
    for name in skill_names:
        category = SKILL_BY_NAME[name]["category"]
        counts[category] = counts.get(category, 0) + 1
    return max(counts, key=counts.get)


def _task_text(task_id: str, family: str, skills: Sequence[str], domain: str,
               index: int) -> Tuple[str, str]:
    feature = FEATURES[family][index % len(FEATURES[family])]
    action = TASK_ACTIONS[index % len(TASK_ACTIONS)]
    quality = OUTPUT_QUALITY[index % len(OUTPUT_QUALITY)]
    title = f"{action} {feature}: {', '.join(skills[:2])}"
    description = (
        f"{action} {feature} для домена {domain}. "
        f"Обязательные компетенции: {', '.join(skills)}. "
        f"В результате нужно {quality}, оставить техническую документацию "
        f"и согласовать изменения с командой. Задача {task_id}."
    )
    return title, description


def _skill_requirements(rng: random.Random, names: Sequence[str]) -> Tuple[RequiredSkill, ...]:
    requirements = []
    for name in names:
        preferred = rng.randint(3, 5)
        requirements.append(RequiredSkill(name=name, min_level=2, preferred_level=preferred))
    return tuple(requirements)


def _covered_by_any(employees: Sequence[Employee], names: Sequence[str]) -> bool:
    return any(
        all(
            (employee.skill_map.get(name) and employee.skill_map[name].level >= 2)
            for name in names
        )
        for employee in employees
    )


def _no_suitable_skills(rng: random.Random, employees: Sequence[Employee]) -> Tuple[str, ...]:
    combinations = list(itertools.combinations(SKILL_NAMES, 3))
    rng.shuffle(combinations)
    for names in combinations:
        if not _covered_by_any(employees, names):
            return tuple(names)
    for size in (4, 5):
        combinations = list(itertools.combinations(SKILL_NAMES, size))
        rng.shuffle(combinations)
        for names in combinations:
            if not _covered_by_any(employees, names):
                return tuple(names)
    raise RuntimeError("Could not build a no-suitable skill combination")


def _qualified(employee: Employee, task: Task) -> bool:
    match = skill_match(employee, task.required_skills)
    if match["missing"] or match["below_minimum"]:
        return False
    return bool(availability_for(employee, task)["available"])


def _probe_task(task_id: str, scenario: str, priority: str, deadline: str,
                estimated_hours: float, requirements: Sequence[RequiredSkill],
                target_employee_id: Optional[str], assigned_at: str, domain: str,
                max_rate: float) -> Task:
    return Task(
        id=task_id, title="probe", description="probe", task_type="probe",
        priority=priority, deadline=deadline, estimated_hours=estimated_hours,
        required_skills=tuple(requirements), target_employee_id=target_employee_id,
        assigned_at=assigned_at, domain=domain, max_hourly_rate=max_rate,
        scenario=scenario, synthetic=True,
    )


def _scenario_constraints_ok(scenario: str, probe: Task, candidate: Employee,
                             employees: Sequence[Employee]) -> bool:
    filtered = filter_candidates(probe, employees, [probe.id])
    min_eligible = {
        "standard": 3,
        "ambiguous_competition": 4,
        "high_load": 3,
        "incomplete_data": 3,
        "missing_skills": 2,
    }.get(scenario, 1)
    if len(filtered.eligible) < min_eligible:
        return False
    if scenario == "ambiguous_competition" and len(filtered.eligible) < 2:
        return False
    if scenario == "missing_skills":
        has_missing = any(
            any(reason["code"] == "missing_required_skills" for reason in row["reasons"])
            for row in filtered.excluded
        )
        if not has_missing:
            return False
    if scenario == "high_load":
        high = sum(
            1 for item in filtered.scored
            if (item.details["availability"].get("avg_load_percent") or 0) >= 80
        )
        if high < 3:
            return False
    if scenario == "incomplete_data":
        if candidate.hourly_rate is not None and candidate.workload:
            return False
    return True


def _make_task_v1(rng: random.Random, index: int, employees: Sequence[Employee],
                  scenario: str) -> Task:
    task_id = f"T{index:03d}"
    assigned_at, deadline = _task_dates(rng)
    domain = rng.choice(DOMAINS)
    priority = rng.choice(PRIORITIES)
    estimated_hours = float(rng.choice(ESTIMATES))
    max_rate = round(rng.uniform(45, 110), 1)

    if scenario == "no_suitable_candidate":
        names = _no_suitable_skills(rng, employees)
        requirements = _skill_requirements(rng, names)
        family = _primary_family(names)
        title, description = _task_text(task_id, family, names, domain, index)
        return Task(
            id=task_id, title=title, description=description,
            task_type=_task_type(family), priority=priority,
            deadline=deadline, estimated_hours=estimated_hours,
            required_skills=requirements, target_employee_id=None,
            assigned_at=assigned_at, domain=domain, max_hourly_rate=max_rate,
            scenario=scenario, synthetic=True,
            notes=("no_suitable: no employee has all required skills at level 2+",),
        )

    target_pool = list(employees)
    if scenario == "high_load":
        target_pool = [item for item in employees if int(item.id[1:]) not in {6, 12, 18, 24, 30}]
    if scenario == "incomplete_data":
        target_pool = [
            item for item in employees
            if item.hourly_rate is None or not item.workload
        ] or target_pool

    target = None
    requirements = None
    target_ids = {item.id for item in target_pool}
    for _ in range(200):
        seed_candidate = rng.choice(target_pool)
        available_names = [item.name for item in seed_candidate.skills if item.level >= 2]
        if len(available_names) < 2:
            continue
        requested = rng.choices([2, 3, 4, 5], weights=[35, 35, 20, 10], k=1)[0]
        names = tuple(rng.sample(available_names, k=min(requested, len(available_names))))
        requirements = _skill_requirements(rng, names)
        probe = _probe_task(
            task_id, scenario, priority, deadline, estimated_hours, requirements,
            seed_candidate.id, assigned_at, domain, max_rate,
        )
        filtered = filter_candidates(probe, employees, [task_id])
        min_eligible = {
            "standard": 3,
            "ambiguous_competition": 4,
            "high_load": 3,
            "incomplete_data": 3,
            "missing_skills": 2,
        }.get(scenario, 1)
        if len(filtered.eligible) < min_eligible:
            continue
        if not _scenario_constraints_ok(scenario, probe, seed_candidate, employees):
            continue

        options = [item for item in filtered.eligible if item.employee.id in target_ids]
        if scenario == "incomplete_data":
            options = [
                item for item in options
                if item.employee.hourly_rate is None or not item.employee.workload
            ]
        if not options:
            continue
        # Hidden label policy: choose from a shortlist by a latent preference
        # that is correlated with, but not identical to, the rule score.  This
        # keeps the target realistic without making it the deterministic top-1.
        def latent(item):
            return (
                0.28 * item.competence
                + 0.24 * item.experience
                + 0.20 * item.availability
                + 0.18 * item.performance
                + 0.10 * item.cost
                + rng.gauss(0.0, 0.06)
            )

        shortlist = sorted(options, key=latent, reverse=True)[:5]
        weights = [0.42, 0.25, 0.15, 0.10, 0.08][:len(shortlist)]
        if scenario == "ambiguous_competition" and len(shortlist) > 1:
            shortlist = shortlist[1:]
            weights = weights[1:]
        target = rng.choices(shortlist, weights=weights, k=1)[0].employee
        break

    if target is None:
        # Deterministic fallback: use an employee with enough level-2 skills and
        # a short period where they have no leave.
        for candidate in employees:
            names = [item.name for item in candidate.skills if item.level >= 2]
            if len(names) < 2:
                continue
            requirements = _skill_requirements(rng, tuple(names[:2]))
            probe = _probe_task(
                task_id, scenario, priority, deadline, estimated_hours, requirements,
                candidate.id, assigned_at, domain, max_rate,
            )
            if _qualified(candidate, probe):
                target = candidate
                break
    if target is None or requirements is None:
        raise RuntimeError(f"Could not create target for task {task_id} ({scenario})")

    names = tuple(item.name for item in requirements)
    family = _primary_family(names)
    title, description = _task_text(task_id, family, names, domain, index)
    return Task(
        id=task_id, title=title, description=description,
        task_type=_task_type(family), priority=priority,
        deadline=deadline, estimated_hours=estimated_hours,
        required_skills=requirements, target_employee_id=target.id,
        assigned_at=assigned_at, domain=domain, max_hourly_rate=max_rate,
        scenario=scenario, synthetic=True,
        notes=(f"scenario={scenario}; target selected from qualified candidates",),
    )


def _generate_v1(seed: int, tasks: int, employees: int) -> Dataset:
    if tasks != sum(SCENARIO_COUNTS.values()):
        raise ValueError(
            f"Scenario counts are fixed to {sum(SCENARIO_COUNTS.values())}; "
            f"requested {tasks}. Change SCENARIO_COUNTS explicitly if needed."
        )
    if employees != 30:
        raise ValueError("The frozen scenario design expects exactly 30 employees.")
    rng = random.Random(seed)
    employee_rows = _employees(seed, employees)
    task_rows = []
    scenario_sequence = []
    for scenario, count in SCENARIO_COUNTS.items():
        scenario_sequence.extend([scenario] * count)
    rng.shuffle(scenario_sequence)
    for index, scenario in enumerate(scenario_sequence, start=1):
        task_rows.append(_make_task_v1(rng, index, employee_rows, scenario))
    rng.shuffle(task_rows)

    manifest = {
        "synthetic": True,
        "dataset_version": "synthetic-v1",
        "dataset_id": f"synthetic_seed{seed}",
        "seed": seed,
        "generator": "matching.experiments.generator:v1",
        "counts": {"employees": len(employee_rows), "tasks": len(task_rows)},
        "scenario_counts": dict(SCENARIO_COUNTS),
        "catalog": {"skills": SKILL_NAMES, "domains": DOMAINS},
        "skill_min_level": 2,
        "target_rules": {
            "base": "the target satisfies every required skill at level 2+ and has availability > 0",
            "no_suitable_candidate": "no target is assigned; no employee has all required skills at level 2+",
            "target_selection": "qualified candidates are ranked by a hidden latent preference (skills, domain, availability, quality, cost) plus noise; the target is sampled from the top-5, not forced to be the rule top-1",
            "ambiguous_competition": "the target is sampled below the top of the latent shortlist when possible",
            "high_load": "the target is not one of the five permanently high-load employees",
            "incomplete_data": "the target may have no rate or no workload records; unknown load is neutral",
            "no_suitable_metrics": "tasks without a target are excluded from Top-1/Top-3/MRR/NDCG",
        },
        "unknown_workload_policy": (
            "neutral 0.5 scaled by present working-day share; full leave is excluded"
        ),
        "embedding_default": "deterministic hashing vectors (synthetic_vectors=true), not Ollama",
        "files": {},
    }
    dataset = Dataset(manifest=manifest, employees=employee_rows, tasks=task_rows)
    validate_dataset(dataset)
    return dataset


def _label_profiles(seed: int, employees: Sequence[Employee]) -> Dict[str, Dict[str, object]]:
    rng = random.Random(f"synthetic-v2-labels:{seed}")
    profiles: Dict[str, Dict[str, object]] = {}
    for employee in employees:
        profiles[employee.id] = {
            "preference": round(rng.random(), 6),
            "domain_affinity": {
                domain: round(rng.random(), 6) for domain in DOMAINS
            },
            "task_type_affinity": {
                task_type: round(rng.random(), 6)
                for task_type in ("backend", "frontend", "data", "devops",
                                  "design", "management")
            },
        }
    return profiles


def _hidden_score(profile: Dict[str, object], domain: str, task_type: str) -> float:
    return round(
        0.50 * float(profile["preference"])
        + 0.30 * float(profile["domain_affinity"][domain])
        + 0.20 * float(profile["task_type_affinity"][task_type]),
        6,
    )


def _eligible_v2(task: Task, employees: Sequence[Employee]) -> List[Employee]:
    """Qualified candidates, without using filter_candidates or a rule score."""
    rows = []
    for employee in employees:
        match = skill_match(employee, task.required_skills)
        if match["missing"] or match["below_minimum"]:
            continue
        if availability_for(employee, task)["available"]:
            rows.append(employee)
    return rows


def _scenario_constraints_ok_v2(scenario: str, probe: Task, candidate: Employee,
                                employees: Sequence[Employee]) -> bool:
    eligible = _eligible_v2(probe, employees)
    min_eligible = {
        "standard": 3,
        "ambiguous_competition": 4,
        "high_load": 3,
        "incomplete_data": 3,
        "missing_skills": 2,
    }.get(scenario, 1)
    if len(eligible) < min_eligible:
        return False
    if scenario == "missing_skills" and not any(
        skill_match(item, probe.required_skills)["missing"] for item in employees
    ):
        return False
    if scenario == "high_load" and sum(
        1 for item in employees
        if (availability_for(item, probe).get("avg_load_percent") or 0) >= 80
    ) < 3:
        return False
    if scenario == "incomplete_data":
        if candidate.hourly_rate is not None and candidate.workload:
            return False
    return True


def _pick_target_v2(task: Task, options: Sequence[Employee],
                    labels: Dict[str, Dict[str, object]], scenario: str,
                    rng: random.Random, task_type: str) -> Employee:
    shortlist = sorted(
        options,
        key=lambda item: (-_hidden_score(labels[item.id], task.domain, task_type), item.id),
    )[:5]
    if scenario == "ambiguous_competition":
        return rng.choice(shortlist[:3])
    weights = [0.42, 0.25, 0.15, 0.10, 0.08][:len(shortlist)]
    return rng.choices(shortlist, weights=weights, k=1)[0]


def _make_task_v2(rng: random.Random, index: int, employees: Sequence[Employee],
                  scenario: str, labels: Dict[str, Dict[str, object]]) -> Task:
    task_id = f"T{index:03d}"
    assigned_at, deadline = _task_dates(rng)
    domain = rng.choice(DOMAINS)
    priority = rng.choice(PRIORITIES)
    estimated_hours = float(rng.choice(ESTIMATES))
    max_rate = round(rng.uniform(45, 110), 1)

    if scenario == "no_suitable_candidate":
        names = _no_suitable_skills(rng, employees)
        requirements = _skill_requirements(rng, names)
        family = _primary_family(names)
        title, description = _task_text(task_id, family, names, domain, index)
        return Task(
            id=task_id, title=title, description=description,
            task_type=_task_type(family), priority=priority,
            deadline=deadline, estimated_hours=estimated_hours,
            required_skills=requirements, target_employee_id=None,
            assigned_at=assigned_at, domain=domain, max_hourly_rate=max_rate,
            scenario=scenario, synthetic=True,
            notes=("no_suitable: no employee has all required skills at level 2+",),
        )

    target_pool = list(employees)
    if scenario == "high_load":
        target_pool = [item for item in employees if int(item.id[1:]) not in {6, 12, 18, 24, 30}]
    if scenario == "incomplete_data":
        target_pool = [
            item for item in employees
            if item.hourly_rate is None or not item.workload
        ] or target_pool

    target = None
    requirements = None
    target_ids = {item.id for item in target_pool}

    def candidates_for(probe: Task) -> List[Employee]:
        options = [
            item for item in _eligible_v2(probe, employees) if item.id in target_ids
        ]
        if scenario == "incomplete_data":
            options = [
                item for item in options
                if item.hourly_rate is None or not item.workload
            ]
        return options

    for _ in range(200):
        seed_candidate = rng.choice(target_pool)
        available_names = [item.name for item in seed_candidate.skills if item.level >= 2]
        if len(available_names) < 2:
            continue
        requested = rng.choices([2, 3, 4, 5], weights=[35, 35, 20, 10], k=1)[0]
        names = tuple(rng.sample(available_names, k=min(requested, len(available_names))))
        requirements = _skill_requirements(rng, names)
        probe = _probe_task(
            task_id, scenario, priority, deadline, estimated_hours, requirements,
            seed_candidate.id, assigned_at, domain, max_rate,
        )
        if not _scenario_constraints_ok_v2(scenario, probe, seed_candidate, employees):
            continue
        options = candidates_for(probe)
        if not options:
            continue
        task_type = _task_type(_primary_family(names))
        target = _pick_target_v2(probe, options, labels, scenario, rng, task_type)
        break

    if target is None:
        for candidate in sorted(target_pool, key=lambda item: item.id):
            names = [item.name for item in candidate.skills if item.level >= 2]
            if len(names) < 2:
                continue
            requirements = _skill_requirements(rng, tuple(names[:2]))
            probe = _probe_task(
                task_id, scenario, priority, deadline, estimated_hours, requirements,
                candidate.id, assigned_at, domain, max_rate,
            )
            if not _scenario_constraints_ok_v2(scenario, probe, candidate, employees):
                continue
            options = candidates_for(probe)
            if not options:
                continue
            task_type = _task_type(_primary_family(names))
            target = _pick_target_v2(probe, options, labels, scenario, rng, task_type)
            break

    if target is None or requirements is None:
        raise RuntimeError(f"Could not create target for task {task_id} ({scenario})")

    names = tuple(item.name for item in requirements)
    family = _primary_family(names)
    title, description = _task_text(task_id, family, names, domain, index)
    return Task(
        id=task_id, title=title, description=description,
        task_type=_task_type(family), priority=priority,
        deadline=deadline, estimated_hours=estimated_hours,
        required_skills=requirements, target_employee_id=target.id,
        assigned_at=assigned_at, domain=domain, max_hourly_rate=max_rate,
        scenario=scenario, synthetic=True,
        notes=(f"scenario={scenario}; target sampled from independent hidden labels",),
    )


def _generate_v2(seed: int, tasks: int, employees: int) -> Dataset:
    if tasks != sum(SCENARIO_COUNTS.values()):
        raise ValueError(
            f"Scenario counts are fixed to {sum(SCENARIO_COUNTS.values())}; "
            f"requested {tasks}. Change SCENARIO_COUNTS explicitly if needed."
        )
    if employees != 30:
        raise ValueError("The frozen scenario design expects exactly 30 employees.")
    rng = random.Random(seed)
    employee_rows = _employees(seed, employees)
    labels = _label_profiles(seed, employee_rows)
    scenario_sequence = []
    for scenario, count in SCENARIO_COUNTS.items():
        scenario_sequence.extend([scenario] * count)
    rng.shuffle(scenario_sequence)
    task_rows = [
        _make_task_v2(rng, index, employee_rows, scenario, labels)
        for index, scenario in enumerate(scenario_sequence, start=1)
    ]
    rng.shuffle(task_rows)

    manifest = {
        "synthetic": True,
        "dataset_version": "synthetic-v2",
        "dataset_id": f"synthetic_v2_seed{seed}",
        "seed": seed,
        "generator": "matching.experiments.generator:v2",
        "counts": {"employees": len(employee_rows), "tasks": len(task_rows)},
        "scenario_counts": dict(SCENARIO_COUNTS),
        "catalog": {"skills": SKILL_NAMES, "domains": DOMAINS},
        "skill_min_level": 2,
        "target_rules": {
            "base": "the target satisfies every required skill at level 2+ and has availability > 0",
            "no_suitable_candidate": "no target is assigned; no employee has all required skills at level 2+",
            "target_selection": (
                "qualified candidates are ranked only by an independent hidden synthetic "
                "label profile (preference, domain affinity, task-type affinity); the target "
                "is sampled from the hidden top-5, never from a rule score"
            ),
            "hidden_labels": (
                "label profiles are generated by a separate RNG and are never written to "
                "employees.jsonl, tasks.jsonl, manifest.json or run artifacts"
            ),
            "ambiguous_competition": (
                "the target is chosen uniformly at random from the hidden top-3 qualified "
                "shortlist"
            ),
            "high_load": "the target is not one of the five permanently high-load employees",
            "incomplete_data": "the target may have no rate or no workload records; unknown load is neutral",
            "no_suitable_metrics": "tasks without a target are excluded from Top-1/Top-3/MRR/NDCG",
        },
        "label_policy": {
            "serialized": False,
            "independent_rng": True,
            "used_for": "synthetic target sampling only",
            "caveat": (
                "Synthetic target labels are not objective ground truth and do not measure "
                "real-world hiring or assignment quality. Metrics are relative to this "
                "synthetic preference process only."
            ),
        },
        "unknown_workload_policy": (
            "neutral 0.5 scaled by present working-day share; full leave is excluded"
        ),
        "embedding_default": "deterministic hashing vectors (synthetic_vectors=true), not Ollama",
        "files": {},
    }
    dataset = Dataset(manifest=manifest, employees=employee_rows, tasks=task_rows)
    validate_dataset(dataset)
    return dataset


def generate_dataset(seed: int = 42, tasks: int = 300, employees: int = 30,
                     dataset_version: str = DATASET_VERSION_DEFAULT) -> Dataset:
    if dataset_version == "synthetic-v1":
        return _generate_v1(seed, tasks, employees)
    if dataset_version == "synthetic-v2":
        return _generate_v2(seed, tasks, employees)
    raise ValueError(f"Unknown dataset version: {dataset_version}")


def validate_dataset(dataset: Dataset) -> None:
    errors = []
    if not dataset.synthetic or not all(item.synthetic for item in dataset.employees):
        errors.append("employees are not marked synthetic")
    if not all(item.synthetic for item in dataset.tasks):
        errors.append("tasks are not marked synthetic")
    if len(dataset.employees) != 30 or len(dataset.tasks) != 300:
        errors.append("expected 30 employees and 300 tasks")
    employee_ids = {item.id for item in dataset.employees}
    task_ids = {item.id for item in dataset.tasks}
    if len(employee_ids) != len(dataset.employees):
        errors.append("duplicate employee ids")
    if len(task_ids) != len(dataset.tasks):
        errors.append("duplicate task ids")
    for employee in dataset.employees:
        if any(item.name not in SKILL_NAMES for item in employee.skills):
            errors.append(f"{employee.id}: unknown skill")
        if any(item.id in task_ids for item in employee.history):
            errors.append(f"{employee.id}: task id leaked into history")
    target_count = 0
    target_eligible = 0
    target_top1 = 0
    scenario_counts = {}
    for task in dataset.tasks:
        scenario_counts[task.scenario] = scenario_counts.get(task.scenario, 0) + 1
        if not (2 <= len(task.required_skills) <= 5):
            errors.append(f"{task.id}: expected 2-5 required skills")
        if any(item.name not in SKILL_NAMES for item in task.required_skills):
            errors.append(f"{task.id}: unknown required skill")
        filtered = filter_candidates(task, dataset.employees, task_ids)
        if task.scenario == "no_suitable_candidate":
            if task.target_employee_id is not None:
                errors.append(f"{task.id}: no-suitable task has a target")
            if filtered.eligible:
                errors.append(f"{task.id}: no-suitable task has eligible candidates")
            continue
        if task.target_employee_id not in employee_ids:
            errors.append(f"{task.id}: target missing")
            continue
        target_count += 1
        target = next(item for item in dataset.employees if item.id == task.target_employee_id)
        match = skill_match(target, task.required_skills)
        if match["missing"] or match["below_minimum"]:
            errors.append(f"{task.id}: target does not satisfy required skills")
        if not availability_for(target, task)["available"]:
            errors.append(f"{task.id}: target is unavailable")
        eligible_ids = [item.employee.id for item in filtered.eligible]
        if target.id in eligible_ids:
            target_eligible += 1
        if eligible_ids and eligible_ids[0] == target.id:
            target_top1 += 1
        if task.target_employee_id in [item.id for item in target.history]:
            errors.append(f"{task.id}: target task appears in employee history")
        if task.scenario == "ambiguous_competition" and len(filtered.eligible) < 2:
            errors.append(f"{task.id}: ambiguous scenario has fewer than two eligible candidates")
        if task.scenario == "missing_skills" and not any(
            any(reason["code"] == "missing_required_skills" for reason in row["reasons"])
            for row in filtered.excluded
        ):
            errors.append(f"{task.id}: missing-skills scenario has no missing-skill candidate")
        if task.scenario == "high_load" and sum(
            1 for item in filtered.scored
            if (item.details["availability"].get("avg_load_percent") or 0) >= 80
        ) < 3:
            errors.append(f"{task.id}: high-load scenario has fewer than three high-load candidates")
        if task.scenario == "incomplete_data" and target.hourly_rate is not None and target.workload:
            errors.append(f"{task.id}: incomplete-data target has no missing fields")
    if target_eligible != target_count:
        errors.append(f"target excluded by hard filters: {target_count - target_eligible}")
    if target_count and target_top1 == target_count:
        errors.append("target is always the top rule candidate")
    if scenario_counts.get("ambiguous_competition", 0) == 0:
        errors.append("no ambiguous scenarios")
    if errors:
        raise ValueError("Dataset validation failed:\n" + "\n".join(errors))


def write_fixture(dataset: Dataset, directory: Path) -> Dict[str, object]:
    return save_dataset(dataset, directory)
