def _skill_levels_for_family(rng: random.Random, family: str) -> Tuple[SkillLevel, ...]:
    primary = list(CATEGORY_SKILLS[family])
    rng.shuffle(primary)
    lower = min(3, len(primary))
    chosen = primary[:rng.randint(lower, min(5, len(primary)))]
    other = [name for name, meta in _meta_items() if meta["category"] != family]
    rng.shuffle(other)
    chosen += other[:rng.randint(1, 2)]
    chosen = list(dict.fromkeys(chosen))
    skills = []
    for index, name in enumerate(chosen):
        if index < 3 and name in primary:
            level = rng.randint(3, 5)
        elif index < 3:
            level = rng.randint(2, 4)
        else:
            level = rng.randint(1, 4)
        skills.append(SkillLevel(
            name=name,
            level=level,
            years_experience=round(max(0.0, (level - 1) * rng.uniform(0.7, 1.8)), 1),
        ))
    return tuple(skills)


